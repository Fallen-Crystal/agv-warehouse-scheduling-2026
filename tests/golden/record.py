"""Record from an archived source tree, or replay its frozen expected results.

    python tests/golden/record.py record --source-root tmp/architecture-baseline
    python tests/golden/record.py replay

The recorder deliberately starts a fresh interpreter with an explicit PYTHONPATH.
Expected values must come from the pre-refactor git archive, never the refactor.
"""

import argparse
import gzip
import hashlib
import json
import os
import platform
import subprocess
import sys
from pathlib import Path
from statistics import median
from time import perf_counter, process_time

ROOT = Path(__file__).resolve().parents[2]
GOLDEN = Path(__file__).resolve().parent
TIMING_KEYS = {"wall_seconds", "cpu_seconds", "decision_cpu_seconds"}
PROFILES = ("legacy", "v4", "v9", "v91", "v91_dense")


def canonical(value):
    return json.dumps(value, sort_keys=True, separators=(",", ":"), allow_nan=False).encode()


def digest(value):
    return hashlib.sha256(canonical(value)).hexdigest()


def source_fingerprint(source_root):
    """Hash all source/assets, excluding interpreter-generated bytecode."""
    source = source_root.resolve() / "src"
    files = {
        str(p.relative_to(source)): hashlib.sha256(p.read_bytes()).hexdigest()
        for p in sorted(source.rglob("*"))
        if p.is_file() and "__pycache__" not in p.parts and p.suffix != ".pyc"
    }
    return dict(sha256=digest(files), files=files)


def normalize(value):
    """Remove only real clock measurements; retain every simulated timestamp."""
    if isinstance(value, dict):
        return {str(k): normalize(v) for k, v in value.items() if k not in TIMING_KEYS}
    if isinstance(value, (list, tuple)):
        return [normalize(v) for v in value]
    return value


def load_golden(directory=GOLDEN):
    manifest = json.loads((directory / "manifest.json").read_text())
    data = json.loads(gzip.decompress((directory / "results.json.gz").read_bytes()))
    if digest(data) != manifest["payload_sha256"]:
        raise ValueError("Golden payload does not match its manifest")
    return manifest, data


def scene(profile, seed):
    from agv.domain import example
    from agv.warehouse.layout import generate as v4
    from agv.warehouse.mixed import generate as v9
    from agv.warehouse.mixed import generate_current as v91

    common = dict(seed=seed, task_count=4, vehicles=2, mode="dynamic", arrival="irregular")
    if profile == "legacy":
        return example(**common, size="medium")
    if profile == "v4":
        return v4(**common, size="small")
    if profile == "v9":
        return v9(**common, size="medium")
    if profile == "v91":
        return v91(**common, size="medium", order_stream_end=120)
    return v91(seed=seed, task_count=12, vehicles=4, size="medium", mode="static")


def legal_solvers(profile):
    from agv.dispatch.registry import SOLVERS, STREAM_SOLVERS

    if profile.startswith("v91"):
        return [s for s in SOLVERS if s in ("baseline", "sipp_stream_dispatch", *STREAM_SOLVERS)]
    return [
        s
        for s in SOLVERS
        if s != "sipp_stream_dispatch"
        and s not in STREAM_SOLVERS
        and (profile == "v9" or not s.startswith("sipp_standby"))
    ]


def execute(solver, scenario):
    from agv.dispatch.registry import run_named
    from agv.evaluation.validation import validate

    start, cpu_start = perf_counter(), process_time()
    result = run_named(solver, scenario)
    elapsed, cpu = perf_counter() - start, process_time() - cpu_start
    if not validate(scenario, result):
        raise ValueError("Independent validator returned false")
    normalized = normalize(result)
    canonical(normalized)
    return normalized, dict(wall_seconds=elapsed, cpu_seconds=cpu)


def record(args):
    from agv.dispatch.registry import SOLVERS

    target = Path(args.output)
    target.mkdir(parents=True, exist_ok=True)
    if (target / "manifest.json").exists() and not args.overwrite:
        raise ValueError("Golden already exists; refusing to replace expected values")
    data, timings, errors = dict(scenes={}, cases=[]), [], []
    start = perf_counter()
    for profile in PROFILES:
        for seed in range(10, 20):
            s = scene(profile, seed)
            scene_key = f"{profile}-{seed}"
            data["scenes"][scene_key] = s.to_dict()
            for solver in legal_solvers(profile):
                key = f"{scene_key}-{solver}"
                try:
                    result, timing = execute(solver, s)
                    data["cases"].append(
                        dict(id=key, scene=scene_key, solver=solver, result=result)
                    )
                    timings.append(dict(id=key, profile=profile, seed=seed, **timing))
                except Exception as error:
                    errors.append(dict(id=key, error=f"{type(error).__name__}: {error}"))
                    print(f"FAILED {key}: {error}", flush=True)
            print(f"recorded {scene_key}: {len(data['cases'])} valid runs so far", flush=True)
        print(f"recorded {profile}: {len(data['cases'])} valid runs so far", flush=True)
    fields = []
    for case in data["cases"]:
        result = case["result"]
        fields.append(
            dict(
                id=case["id"],
                result_sha256=digest(result),
                paths_sha256=digest(result["paths"]),
                assignments_sha256=digest(result["assignments"]),
                weighted_score=result.get("weighted_score"),
                feasible=result["feasible"],
                completed=result["completed"],
            )
        )
    source = Path(args.source_root)
    source_hashes = {
        str(p.relative_to(source)): hashlib.sha256(p.read_bytes()).hexdigest()
        for p in sorted((source / "src").rglob("*.py"))
    }
    manifest = dict(
        format="agv-architecture-golden-v1",
        baseline_commit=args.baseline_commit,
        source_sha256=digest(source_hashes),
        python=platform.python_version(),
        normalization_excluded_keys=sorted(TIMING_KEYS),
        seeds=list(range(10, 20)),
        registered_solvers=list(SOLVERS),
        profiles=list(PROFILES),
        case_count=len(data["cases"]),
        expected_case_count=580,
        payload_sha256=digest(data),
        recording_wall_seconds=perf_counter() - start,
        errors=errors,
        cases=fields,
        timings=timings,
    )
    (target / "results.json.gz").write_bytes(gzip.compress(canonical(data), mtime=0))
    (target / "manifest.json").write_text(json.dumps(manifest, indent=2) + "\n")
    print(json.dumps({k: manifest[k] for k in ("case_count", "errors", "recording_wall_seconds")}))
    return 1 if errors or len(data["cases"]) != 580 else 0


def replay(directory=GOLDEN, *, seeds=None, verbose=False):
    from agv.dispatch.registry import SOLVERS
    from agv.domain import Scenario

    manifest, data = load_golden(directory)
    if list(SOLVERS) != manifest["registered_solvers"]:
        raise ValueError("Registered solver names/order changed since baseline")
    errors, timings = [], []
    for case in data["cases"]:
        if seeds is not None and int(case["scene"].rsplit("-", 1)[1]) not in seeds:
            continue
        try:
            s = Scenario.from_dict(data["scenes"][case["scene"]])
            actual, timing = execute(case["solver"], s)
            timings.append(dict(id=case["id"], **timing))
            if canonical(actual) != canonical(case["result"]):
                changed = sorted(
                    k
                    for k in actual.keys() | case["result"].keys()
                    if k not in actual
                    or k not in case["result"]
                    or canonical(actual[k]) != canonical(case["result"][k])
                )
                errors.append(dict(id=case["id"], changed=changed))
                if verbose:
                    print(f"DIFFERENCE {case['id']}: {', '.join(changed)}", flush=True)
        except Exception as error:
            errors.append(dict(id=case["id"], error=f"{type(error).__name__}: {error}"))
            if verbose:
                print(f"FAILED {case['id']}: {error}", flush=True)
        if verbose and len(timings) % 20 == 0:
            print(f"replayed {len(timings)} cases; differences={len(errors)}", flush=True)
    baseline_times = {row["id"]: row for row in manifest["timings"]}
    groups = {}
    for row in timings:
        profile = row["id"].split("-", 1)[0]
        group = groups.setdefault(profile, {"baseline": [], "replay": []})
        group["baseline"].append(baseline_times[row["id"]]["cpu_seconds"])
        group["replay"].append(row["cpu_seconds"])
    comparison = {}
    for profile, group in groups.items():
        before, after = median(group["baseline"]), median(group["replay"])
        comparison[profile] = dict(
            baseline_median_cpu_seconds=before,
            replay_median_cpu_seconds=after,
            baseline_over_replay=before / after,
        )
    return dict(
        baseline_commit=manifest["baseline_commit"],
        baseline_payload_sha256=manifest["payload_sha256"],
        runs=len(timings),
        differences=errors,
        timings=timings,
        timing_summary=comparison,
    )


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("command", choices=("record", "replay"))
    parser.add_argument("--source-root", type=Path, default=ROOT)
    parser.add_argument("--output", type=Path, default=GOLDEN)
    parser.add_argument("--report", type=Path, help="Separate replay evidence JSON file")
    parser.add_argument("--baseline-commit", default="81dc59313898687be0e64ff9ba19b236a9f8dc06")
    parser.add_argument("--overwrite", action="store_true")
    parser.add_argument("--seed", type=int, action="append", help="Replay only selected seed(s)")
    parser.add_argument("--worker", action="store_true", help=argparse.SUPPRESS)
    args = parser.parse_args()
    if not args.worker:
        environment = {**os.environ, "PYTHONPATH": str(args.source_root.resolve() / "src")}
        return subprocess.call(
            [sys.executable, __file__, *sys.argv[1:], "--worker"], env=environment
        )
    import agv

    if Path(agv.__file__).resolve().parent != (args.source_root / "src/agv").resolve():
        raise ValueError("Imported agv is not from the requested source tree")
    if args.command == "record":
        if args.source_root.resolve() == ROOT:
            raise ValueError("Record requires a separate frozen pre-refactor source tree")
        return record(args)
    before = source_fingerprint(args.source_root)
    report = replay(
        args.output, seeds=set(args.seed) if args.seed is not None else None, verbose=True
    )
    after = source_fingerprint(args.source_root)
    report["source_before"] = before
    report["source_after"] = after
    report["source_unchanged"] = before == after
    if before != after:
        report["differences"].append(dict(error="Source changed during replay"))
    report["source_root"] = str(args.source_root.resolve())
    destination = args.report or args.output / "last-replay.json"
    destination.write_text(json.dumps(report, indent=2) + "\n")
    print(json.dumps({k: report[k] for k in ("runs", "differences", "timing_summary")}))
    return bool(report["differences"])


if __name__ == "__main__":
    raise SystemExit(main())
